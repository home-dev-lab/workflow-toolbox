import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { MAX_CRITIC_ROUNDS, MAX_REVIEW_ROUNDS, PHASES } from '../../plugin/bin/lib/lifecycle-state-machine.mjs'

const root = fileURLToPath(new URL('../..', import.meta.url))
const target = path.join(root, 'plugin', 'hooks', 'lifecycle-phases.js')
const LOOP_BOUNDS = { plan: MAX_CRITIC_ROUNDS, critic: MAX_CRITIC_ROUNDS, review: MAX_REVIEW_ROUNDS, refutation: MAX_REVIEW_ROUNDS, harden: MAX_REVIEW_ROUNDS - 1 }
const expected = `// Generated by toolkit/scripts/mirror-lifecycle-phases.mjs. Do not edit.\nexport const PHASES = Object.freeze(${JSON.stringify(PHASES)});\nexport const LOOP_BOUNDS = Object.freeze(${JSON.stringify(LOOP_BOUNDS)});\n`

if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== expected) {
    console.error('plugin/hooks/lifecycle-phases.js is stale; run pnpm mirror:lifecycle-phases')
    process.exitCode = 1
  }
} else {
  fs.writeFileSync(target, expected)
}
